#!/usr/bin/env python3
"""Render server-side configs for amnezia-mesh.

Reads config/server.env + config/peers.db and writes:
  config/awg0.conf    - full AWG server config (interface + peers)
  config/dnsmasq.conf - dnsmasq for MagicDNS (sidecar shares awg netns)
  config/peers.hosts  - MagicDNS host records (dnsmasq --addn-hosts; re-read
                        on SIGHUP so peer changes don't restart the sidecar)
  config/start.sh     - container entrypoint: awg-quick (+ userspace
                        fallback) + iptables bootstrap
  config/custom.hosts - created when missing only; operator DNS records
                        (`awg-mesh dns`) — user data, never re-rendered

Usage: render.py [all|awg0|dnsmasq|peers.hosts|start.sh]
"""
import ipaddress
import os
import re
import stat
import sys

ROOT = os.environ.get("AWG_MESH_ROOT") or os.path.dirname(
    os.path.dirname(os.path.abspath(__file__)))
ENV_FILE = os.path.join(ROOT, "config", "server.env")
PEERS_DB = os.path.join(ROOT, "config", "peers.db")


def load_env(path):
    env = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    return env


def load_peers(path):
    peers = []
    if not os.path.exists(path):
        return peers
    with open(path) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 5:
                name, ip, pub, psk, created = parts[:5]
                if not re.fullmatch(r"[a-z0-9-]{1,32}", name):
                    sys.exit(f"render: invalid peer name in db: {name!r}")
                peers.append({"name": name, "ip": ip, "pub": pub,
                              "psk": psk, "created": created})
    return peers


def hub_ip(subnet):
    net = ipaddress.ip_network(subnet)
    return str(net.network_address + 1)


# AmneziaWG obfuscation parameter names, in render order. Shared with
# adopt.py (conf key -> OBF_*) — single source of truth for the key set.
OBF_KEYS = ["Jc", "Jmin", "Jmax", "S1", "S2", "S3", "S4",
            "H1", "H2", "H3", "H4", "HeaderProtectionKey",
            "ContentPaddingAddition", "RekeyAfterTime", "RekeyTimeout",
            "RejectAfterTime", "KeepaliveTimeout", "MaxHandshakeAttempts",
            "RandomTrailers", "DisableCookies"]


def obf_lines(env, indent=""):
    out = []
    for k in OBF_KEYS:
        v = env.get(f"OBF_{k.upper()}")
        if v:
            out.append(f"{indent}{k} = {v}")
    return out


def render_awg0(env, peers):
    keepalive = env.get("SERVER_KEEPALIVE", "25")
    lines = [
        "# Generated by amnezia-mesh (render.py). Do not edit by hand:",
        "# changes are overwritten on every `awg-mesh peer` operation.",
        "[Interface]",
        f"PrivateKey = {env['SERVER_PRIV']}",
        f"Address = {hub_ip(env['AWG_MESH_SUBNET'])}/{ipaddress.ip_network(env['AWG_MESH_SUBNET']).prefixlen}",
        f"ListenPort = {env.get('LISTEN_PORT', '41480')}",
        f"MTU = {env.get('MTU', '1280')}",
    ]
    lines += obf_lines(env)
    for p in peers:
        lines += [
            "[Peer]",
            f"# {p['name']} (added {p['created']})",
            f"PublicKey = {p['pub']}",
            f"PresharedKey = {p['psk']}",
            f"AllowedIPs = {p['ip']}/32",
            f"PersistentKeepalive = {keepalive}",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_dnsmasq(env, peers):
    domain = env.get("AWG_MESH_DOMAIN", "awg")
    lines = [
        "# Generated by amnezia-mesh (render.py).",
        "no-resolv",
        "listen-address=127.0.0.1",
        "interface=awg0",
        "bind-interfaces",
        "domain-needed",
        "bogus-priv",
        f"server={env.get('AWG_MESH_DNS1', '1.1.1.1')}",
    ]
    if env.get("AWG_MESH_DNS2"):
        lines.append(f"server={env['AWG_MESH_DNS2']}")
    # Host records live in a separate --addn-hosts file (rendered below as
    # config/peers.hosts) rather than inline: dnsmasq re-reads addn-hosts on
    # SIGHUP, so peer add/rename reload MagicDNS without restarting the
    # sidecar. (The main config file is never re-read by dnsmasq.)
    lines.append("addn-hosts=/etc/peers.hosts")
    # Operator records managed by `awg-mesh dns` (config/custom.hosts). The
    # file is user data: render only creates it when missing, never
    # overwrites it.
    lines.append("addn-hosts=/etc/custom.hosts")
    return "\n".join(lines) + "\n"


# Header of config/custom.hosts (the dnsmasq --addn-hosts input for
# `awg-mesh dns` records). Written only when the file does not exist yet.
CUSTOM_HOSTS_HEADER = (
    "# amnezia-mesh custom DNS records (config/custom.hosts).\n"
    "# Managed by `awg-mesh dns add|remove`; dnsmasq re-reads this file on\n"
    "# SIGHUP, so changes apply without restarting the sidecar.\n"
)


def render_peers_hosts(env, peers):
    """/etc/hosts-format file for dnsmasq --addn-hosts: <ip> <fqdn>."""
    domain = env.get("AWG_MESH_DOMAIN", "awg")
    lines = [
        "# Generated by amnezia-mesh (render.py).",
        f"{hub_ip(env['AWG_MESH_SUBNET'])}\thub.{domain}",
    ]
    for p in peers:
        lines.append(f"{p['ip']}\t{p['name']}.{domain}")
    return "\n".join(lines) + "\n"


def render_start_sh(env):
    subnet = env["AWG_MESH_SUBNET"]
    mtu = int(env.get("MTU", "1280"))
    mss = mtu - 40
    rdp = env.get("AWG_MESH_RDP_REJECT", "0") == "1"
    rdp_rule = ""
    if rdp:
        rdp_rule = (
            "# RDP UDP/3389 reject: forces instant TCP fallback, avoids starving\n"
            "# graphics channel across the tunnel (see README).\n"
            "iptables -I FORWARD 1 -i awg0 -p udp --dport 3389 -j REJECT --reject-with icmp-port-unreachable"
        )
    return f"""#!/bin/sh
# Generated by amnezia-mesh (render.py). Subnet: {subnet}.
echo "amnezia-mesh: starting"
sysctl -w net.ipv4.ip_forward=1 2>/dev/null || true
awg-quick down /opt/amnezia/awg/awg0.conf 2>/dev/null
if awg-quick up /opt/amnezia/awg/awg0.conf; then
  echo "amnezia-mesh: backend up"
else
  # VPS without the kernel module (or a tools/module generation mismatch):
  # force the userspace implementation shipped in the image. Same config,
  # same obfuscation — ~30-50% CPU overhead is the price.
  echo "amnezia-mesh: kernel backend failed, falling back to userspace amneziawg-go"
  awg-quick down /opt/amnezia/awg/awg0.conf 2>/dev/null
  if ! WG_QUICK_USERSPACE_IMPLEMENTATION=amneziawg-go awg-quick up /opt/amnezia/awg/awg0.conf; then
    echo "amnezia-mesh: awg-quick failed"; exit 1
  fi
fi

SUBNET={subnet}
IFACE=$(ip route show default 2>/dev/null | awk 'NR==1 {{print $5}}')

iptables -A INPUT -i awg0 -j ACCEPT
iptables -A FORWARD -i awg0 -j ACCEPT
iptables -A OUTPUT -o awg0 -j ACCEPT
if [ -n "$IFACE" ]; then
  iptables -A FORWARD -i awg0 -o "$IFACE" -s "$SUBNET" -j ACCEPT
  iptables -t nat -A POSTROUTING -s "$SUBNET" -o "$IFACE" -j MASQUERADE
fi
iptables -A FORWARD -m state --state ESTABLISHED,RELATED -j ACCEPT

# MSS clamp both directions: {mss} = MTU {mtu} - 40. Explicit --set-mss,
# NOT --clamp-mss-to-pmtu (that one uses the outgoing route MTU and misses
# the download direction).
iptables -t mangle -A FORWARD -i awg0 -p tcp --tcp-flags SYN,RST SYN \\
  -m tcpmss --mss {mss + 1}:65535 -j TCPMSS --set-mss {mss}
iptables -t mangle -A FORWARD -o awg0 -p tcp --tcp-flags SYN,RST SYN \\
  -m tcpmss --mss {mss + 1}:65535 -j TCPMSS --set-mss {mss}
{rdp_rule}
exec tail -f /dev/null
"""


def write(path, content, executable=False, mode=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
    if mode is not None:
        os.chmod(path, mode)
    elif executable:
        os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def ensure_custom_hosts(out_dir):
    """Create config/custom.hosts (dnsmasq --addn-hosts input for `awg-mesh
    dns` records) when missing. User data afterwards — never overwritten."""
    path = os.path.join(out_dir, "custom.hosts")
    if not os.path.exists(path):
        write(path, CUSTOM_HOSTS_HEADER)


def render_all():
    env = load_env(ENV_FILE)
    peer_list = load_peers(PEERS_DB)
    out_dir = os.path.join(ROOT, "config")
    # 0o600: awg-quick warns on world-readable configs that contain secrets.
    write(os.path.join(out_dir, "awg0.conf"), render_awg0(env, peer_list),
          mode=0o600)
    write(os.path.join(out_dir, "dnsmasq.conf"), render_dnsmasq(env, peer_list))
    write(os.path.join(out_dir, "peers.hosts"),
          render_peers_hosts(env, peer_list))
    write(os.path.join(out_dir, "start.sh"), render_start_sh(env),
          executable=True)
    ensure_custom_hosts(out_dir)
    return len(peer_list)


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    if which == "all":
        print(f"rendered: all ({render_all()} peers)")
        return
    env = load_env(ENV_FILE)
    peer_list = load_peers(PEERS_DB)
    out_dir = os.path.join(ROOT, "config")
    if which == "awg0":
        write(os.path.join(out_dir, "awg0.conf"), render_awg0(env, peer_list),
              mode=0o600)
    elif which == "dnsmasq":
        write(os.path.join(out_dir, "dnsmasq.conf"),
              render_dnsmasq(env, peer_list))
    elif which == "peers.hosts":
        write(os.path.join(out_dir, "peers.hosts"),
              render_peers_hosts(env, peer_list))
    elif which == "start.sh":
        write(os.path.join(out_dir, "start.sh"), render_start_sh(env),
              executable=True)
    else:
        sys.exit("usage: render.py [all|awg0|dnsmasq|peers.hosts|start.sh]")
    print(f"rendered: {which} ({len(peer_list)} peers)")


if __name__ == "__main__":
    main()
